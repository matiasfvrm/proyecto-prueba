/**
 * Generates supabase/seed.sql from the TypeScript catalog so the database and the
 * bundled catalog never drift. Demo profiles and their activity are excluded:
 * a real database starts with no contributors.
 *
 *   npm run db:seed-sql
 */
import { writeFileSync } from "node:fs";
import { seedCatalog } from "../src/lib/data/seed";
import { productionCatalog } from "../src/lib/data/catalog";

const c = productionCatalog(seedCatalog);
const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return `array[${v.map(q).join(",")}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (v: string[]) => (v.length ? q(v) : "'{}'::text[]");

const out: string[] = ["-- Generated by scripts/generate-seed-sql.ts. Do not edit by hand.", "begin;"];
for (const s of c.sources)
  out.push(`insert into sources values (${q(s.id)},${q(s.title)},${q(s.publisher)},${q(s.year ?? null)},${q(s.url)},${q(s.type)}) on conflict (id) do nothing;`);
for (const p of c.problems) {
  out.push(
    `insert into problems (id,slug,title,category,summary,why_it_matters,definition,difficulty,status,skills,causes,claims,approaches,limitations,validation_criteria,created_at,updated_at) values (${[
      q(p.id), q(p.slug), q(p.title), q(p.category), q(p.summary), q(p.whyItMatters), q(p.definition), q(p.difficulty), q(p.status), arr(p.skills),
      json(p.causes), json(p.claims), json(p.approaches), arr(p.limitations), arr(p.validationCriteria), q(p.createdAt), q(p.updatedAt),
    ].join(",")}) on conflict (id) do nothing;`,
  );
  for (const s of p.sourceIds) out.push(`insert into problem_sources values (${q(p.id)},${q(s)}) on conflict do nothing;`);
}
for (const p of c.problems) for (const r of p.relatedProblemIds) out.push(`insert into related_problems values (${q(p.id)},${q(r)}) on conflict do nothing;`);
for (const x of c.questions)
  out.push(`insert into research_questions values (${[q(x.id), q(x.problemId), q(x.question), q(x.whyItMatters), q(x.existingKnowledge), arr(x.uncertainties), arr(x.suggestedApproaches), arr(x.skills), q(x.status)].join(",")}) on conflict (id) do nothing;`);
for (const h of c.hypotheses) out.push(`insert into hypotheses values (${q(h.id)},${q(h.questionId)},${q(h.statement)},${q(h.status)}) on conflict (id) do nothing;`);
for (const e of c.experiments) out.push(`insert into experiments values (${q(e.id)},${q(e.hypothesisId)},${q(e.title)},${q(e.design)},${q(e.status)}) on conflict (id) do nothing;`);
for (const s of c.solutions) out.push(`insert into solutions values (${q(s.id)},${q(s.problemId)},${q(s.title)},${q(s.summary)},${q(s.status)},${arr(s.questionIds)}) on conflict (id) do nothing;`);
for (const t of c.tasks)
  out.push(
    `insert into tasks (id,problem_id,question_id,title,objective,description,deliverable,skills,difficulty,effort,acceptance_criteria,status,blocked_reason) values (${[
      q(t.id), q(t.problemId), q(t.questionId), q(t.title), q(t.objective), q(t.description), q(t.deliverable), arr(t.skills), q(t.difficulty), q(t.effort), arr(t.acceptanceCriteria), q(t.status), q(t.blockedReason ?? null),
    ].join(",")}) on conflict (id) do nothing;`,
  );
out.push("commit;", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`Wrote supabase/seed.sql (${c.problems.length} problems, ${c.questions.length} questions, ${c.tasks.length} tasks).`);
